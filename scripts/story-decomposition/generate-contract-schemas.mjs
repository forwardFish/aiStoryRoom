function obj(properties, required = Object.keys(properties), extra = {}) {
  return { type: "object", additionalProperties: false, properties, required, ...extra };
}

function arr(items, minItems = 0, extra = {}) {
  return { type: "array", items, minItems, ...extra };
}

function enumString(values) {
  return { type: "string", enum: values };
}

function schema(id, root) {
  return { $schema: DRAFT, $id: `https://our-many-worlds.local/schemas/${id}.schema.json`, title: id, ...root };
}

